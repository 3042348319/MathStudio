void applyAppIcon(GLFWwindow* window) {
    if (window == nullptr) {
        return;
    }

    int count = 0;
    const AppIconImage* images = appIconImages(count);
    std::vector<GLFWimage> glfwImages;
    glfwImages.reserve(static_cast<std::size_t>(count));

    for (int i = 0; i < count; ++i) {
        GLFWimage image{};
        image.width = images[i].width;
        image.height = images[i].height;
        image.pixels = const_cast<unsigned char*>(images[i].pixels);
        glfwImages.push_back(image);
    }

    glfwSetWindowIcon(window, count, glfwImages.data());
}

void applyDarkWindowFrame(GLFWwindow* window) {
    if (window == nullptr) {
        return;
    }

    HWND hwnd = glfwGetWin32Window(window);
    if (hwnd == nullptr) {
        return;
    }

    // Windows 10 1809+ 使用属性 20; 早期版本使用 19。
    BOOL dark = TRUE;
    HRESULT result = DwmSetWindowAttribute(
        hwnd, 20, &dark, sizeof(dark));
    if (FAILED(result)) {
        DwmSetWindowAttribute(hwnd, 19, &dark, sizeof(dark));
    }

    // 标题栏边框也使用近黑色。
    const COLORREF border = RGB(24, 25, 29);
    DwmSetWindowAttribute(hwnd, 34, &border, sizeof(border));
}
